import Foundation

/// A made-up 18-hole layout built around any starting point, so the whole app can be tried
/// anywhere (including the Simulator) before real course data is wired up.
enum DemoCourse {
    static let id = "demo-links"
    private static let pars = [4, 4, 3, 5, 4, 4, 3, 4, 5, 4, 3, 4, 5, 4, 4, 3, 4, 5]
    private static let lengths: [Int: Double] = [3: 150, 4: 355, 5: 470] // meters

    static func make(firstTee: Coordinate) -> Course {
        var holes: [Hole] = []
        var tee = firstTee
        for (i, par) in pars.enumerated() {
            let number = i + 1
            // Snake the holes north and south, stepping east, so they never overlap.
            let bearing = i.isMultiple(of: 2) ? 2.0 : 182.0
            let length = lengths[par]!
            let center = Geo.offset(tee, meters: length, bearing: bearing)
            var hazards = [
                Hazard(id: "\(number)-greenside",
                       kind: .bunker,
                       near: Geo.offset(Geo.offset(tee, meters: length - 22, bearing: bearing), meters: 18, bearing: bearing - 90),
                       carry: Geo.offset(Geo.offset(tee, meters: length - 8, bearing: bearing), meters: 18, bearing: bearing - 90)),
            ]
            if par == 4 {
                hazards.append(Hazard(id: "\(number)-fairway",
                                      kind: .bunker,
                                      near: Geo.offset(Geo.offset(tee, meters: 210, bearing: bearing), meters: 20, bearing: bearing + 90),
                                      carry: Geo.offset(Geo.offset(tee, meters: 235, bearing: bearing), meters: 20, bearing: bearing + 90)))
            }
            if par == 5 {
                hazards.append(Hazard(id: "\(number)-creek",
                                      kind: .water,
                                      near: Geo.offset(tee, meters: 250, bearing: bearing),
                                      carry: Geo.offset(tee, meters: 275, bearing: bearing)))
            }
            holes.append(Hole(number: number,
                              par: par,
                              tee: tee,
                              greenFront: Geo.offset(center, meters: -14, bearing: bearing),
                              greenCenter: center,
                              greenBack: Geo.offset(center, meters: 14, bearing: bearing),
                              hazards: hazards))
            tee = Geo.offset(center, meters: 60, bearing: 92)
        }
        return Course(id: id, name: "Gimme Demo Links", holes: holes, source: "Demo layout generated by Gimme")
    }
}
