import Foundation

/// A made-up 18-hole layout built around any starting point, so the whole app can be tried
/// anywhere (including the Simulator) before real course data is wired up.
enum DemoCourse {
    static let id = "demo-links"
    private static let pars = [4, 4, 3, 5, 4, 4, 3, 4, 5, 4, 3, 4, 5, 4, 4, 3, 4, 5]
    private static let lengths: [Int: Double] = [3: 150, 4: 355, 5: 470] // meters
    /// Stroke index: odd numbers on the front nine, even on the back, like most scorecards.
    private static let handicaps = [7, 1, 17, 11, 3, 9, 15, 5, 13, 8, 18, 2, 12, 6, 4, 16, 10, 14]

    static func make(firstTee: Coordinate) -> Course {
        let holes = layout(firstTee: firstTee, pars: pars, meters: pars.map { lengths[$0]! }, handicaps: handicaps)
        var course = Course(id: id, name: "Gimme Demo Links", holes: holes, source: "Demo layout generated by Gimme")
        for i in course.holes.indices {
            course.holes[i].yardages = yardages(meters: pars.map { lengths[$0]! }[i], par: pars[i])
        }
        course.tees = [("Blue", "blue", 71.8, 131), ("White", "white", 69.9, 125), ("Red", "red", 67.2, 117)].map { tee in
            TeeSet(name: tee.0, color: tee.1, rating: tee.2, slope: tee.3, par: course.par, yardage: course.total(tee.0))
        }
        return course
    }

    /// Stand-in hole positions for a course with a scorecard but no map yet, laid out from the
    /// course's location using the scorecard yardages. Marked `needsMapping` so the screen says so.
    static func provisional(id: String, name: String, around center: Coordinate, card: ScorecardService.Scorecard) -> Course {
        let longest = card.tees.max { $0.yardage < $1.yardage }?.name
        let sorted = card.holes.sorted { $0.number < $1.number }
        let pars = sorted.map { $0.par ?? 4 }
        let meters = sorted.map { hole -> Double in
            let yards = longest.flatMap { tee in hole.yardages.first { $0.key.caseInsensitiveCompare(tee) == .orderedSame }?.value }
            return Double(yards ?? ([3: 165, 4: 390, 5: 515][hole.par ?? 4] ?? 390)) * Geo.metersPerYard
        }
        var course = Course(id: id, name: name,
                            holes: layout(firstTee: center, pars: pars, meters: meters, handicaps: sorted.map(\.handicap)),
                            source: "Stand-in layout until the holes are mapped")
        course.needsMapping = true
        return course
    }

    private static func layout(firstTee: Coordinate, pars: [Int], meters: [Double], handicaps: [Int?]) -> [Hole] {
        var holes: [Hole] = []
        var tee = firstTee
        for (i, par) in pars.enumerated() {
            let number = i + 1
            // Snake the holes north and south, stepping east, so they never overlap.
            let bearing = i.isMultiple(of: 2) ? 2.0 : 182.0
            let length = meters[i]
            let center = Geo.offset(tee, meters: length, bearing: bearing)
            var hazards = [
                Hazard(id: "\(number)-greenside",
                       kind: .bunker,
                       near: Geo.offset(Geo.offset(tee, meters: length - 22, bearing: bearing), meters: 18, bearing: bearing - 90),
                       carry: Geo.offset(Geo.offset(tee, meters: length - 8, bearing: bearing), meters: 18, bearing: bearing - 90)),
            ]
            if par == 4 {
                hazards.append(Hazard(id: "\(number)-fairway",
                                      kind: .bunker,
                                      near: Geo.offset(Geo.offset(tee, meters: 210, bearing: bearing), meters: 20, bearing: bearing + 90),
                                      carry: Geo.offset(Geo.offset(tee, meters: 235, bearing: bearing), meters: 20, bearing: bearing + 90)))
            }
            if par == 5 {
                hazards.append(Hazard(id: "\(number)-creek",
                                      kind: .water,
                                      near: Geo.offset(tee, meters: 250, bearing: bearing),
                                      carry: Geo.offset(tee, meters: 275, bearing: bearing)))
            }
            holes.append(Hole(number: number,
                              par: par,
                              tee: tee,
                              greenFront: Geo.offset(center, meters: -14, bearing: bearing),
                              greenCenter: center,
                              greenBack: Geo.offset(center, meters: 14, bearing: bearing),
                              hazards: hazards,
                              handicap: handicaps.indices.contains(i) ? handicaps[i] : nil))
            tee = Geo.offset(center, meters: 60, bearing: 92)
        }
        return holes
    }

    /// Back, middle and forward tee yardages for a hole of this length.
    private static func yardages(meters: Double, par: Int) -> [String: Int] {
        let blue = Int((meters / Geo.metersPerYard).rounded())
        let step = par == 3 ? 15 : 25
        return ["Blue": blue, "White": blue - step, "Red": blue - step * 3]
    }
}
